// Generates src/content/types.gen.ts from curriculum/schema/*.v2.output.schema.json
// (API output shape: defaults filled), exported from the Pydantic models.
// `--check` fails when the committed file is stale (used by the unit tests).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schemaDir = path.resolve(root, "../curriculum/schema");
export const outFile = path.join(root, "src/content/types.gen.ts");

const banner =
  "/* Generated by scripts/gen-content-types.mjs from curriculum/schema. Do not edit. */";

// Pydantic titles every property, which would turn each field into its own
// exported alias (Id1, Type1, ...). Keep titles only on $defs (interface names).
// `node` is always a schema; maps keyed by user names ($defs, properties) are
// walked value by value so a field literally called "title" survives.
function stripPropertyTitles(node, keep = false) {
  if (Array.isArray(node)) return node.forEach((child) => stripPropertyTitles(child));
  if (!node || typeof node !== "object") return;
  if (!keep && typeof node.title === "string") delete node.title;
  for (const [key, child] of Object.entries(node)) {
    if (key === "$defs")
      for (const definition of Object.values(child)) stripPropertyTitles(definition, true);
    else if (key === "properties" || key === "patternProperties")
      for (const property of Object.values(child)) stripPropertyTitles(property);
    else if (child && typeof child === "object") stripPropertyTitles(child);
  }
}

export async function render() {
  const parts = [banner];
  for (const [file, name] of [
    ["content.v2.output.schema.json", "LessonContent"],
    ["onboarding.v2.output.schema.json", "Onboarding"],
  ]) {
    const schema = JSON.parse(fs.readFileSync(path.join(schemaDir, file), "utf8"));
    stripPropertyTitles(schema, true);
    schema.title = name;
    parts.push(
      await compile(schema, name, {
        bannerComment: "",
        additionalProperties: false,
        unreachableDefinitions: false,
        style: { singleQuote: false, printWidth: 100 },
      }),
    );
  }
  // Both documents share block definitions; keep the first declaration of each.
  const seen = new Set();
  const out = [];
  for (const chunk of parts.join("\n").split(/\n(?=export )/)) {
    const name = chunk.match(/^export (?:interface|type) (\w+)/)?.[1];
    if (name && seen.has(name)) continue;
    if (name) seen.add(name);
    out.push(chunk);
  }
  return out.join("\n").trimEnd() + "\n";
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const text = await render();
  if (process.argv.includes("--check")) {
    const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, "utf8") : "";
    if (current !== text) {
      console.error("src/content/types.gen.ts is stale; run npm run content:types");
      process.exit(1);
    }
    console.log("content types up to date");
  } else {
    fs.writeFileSync(outFile, text);
    console.log("wrote src/content/types.gen.ts");
  }
}
